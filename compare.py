#!/usr/bin/env python3
"""Combine reviews/*.json into one side-by-side comparison.

Usage:
  python3 compare.py      writes comparison.md and comparison.csv

Each plugin gets one row: its lane and installs from shortlist.csv, a Pass / Partial / Fail
tally over the judged checks, then the status of every check and every standard task.
Rows are sorted by Pass count, then by Fail count (fewer first). The tally is a plain count
with no weighting, so it is a starting point for reading the reviews, not a ranking.
"""
import csv
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REVIEWS = HERE / "reviews"
SHORTLIST = HERE / "shortlist.csv"
CHECKLIST = HERE / "CHECKLIST.md"

TASKS = [f"T{n}" for n in range(1, 9)]
SHORT = {"Pass": "✅", "Partial": "🟡", "Fail": "❌", "Unknown": "?", "N/A": "–", "Info": "ℹ️"}


def check_ids():
    """Check IDs in the order they appear in the checklist tables."""
    return [i for i in re.findall(r"^\| ([A-Z]+(?:-[A-Z]+)?) \|", CHECKLIST.read_text(), re.M) if i != "ID"]


def load():
    shortlist = {r["slug"]: r for r in csv.DictReader(SHORTLIST.open())}
    rows = []
    for path in sorted(REVIEWS.glob("*.json")):
        review = json.loads(path.read_text())
        checks = review["checks"]
        tasks = checks.get("CAP-TASKS", {}).get("value") or {}
        tools = checks.get("CAP-TOOLS", {}).get("value") or {}
        meta = shortlist.get(review["slug"], {})
        statuses = [c["status"] for c in checks.values()]
        rows.append({
            "slug": review["slug"],
            "version": review.get("version", ""),
            "lane": meta.get("lane", ""),
            "installs": int(meta.get("active_installs") or 0),
            "pass": statuses.count("Pass"),
            "partial": statuses.count("Partial"),
            "fail": statuses.count("Fail"),
            "tools": tools.get("count", "") if isinstance(tools, dict) else "",
            "checks": {k: c["status"] for k, c in checks.items()},
            "tasks": {t: (tasks.get(t) or {}).get("status", "") for t in TASKS},
        })
    rows.sort(key=lambda r: (-r["pass"], r["fail"], -r["installs"]))
    return rows


def judged(ids):
    """Checks that carry a judgement (the CAP-* ones are Info)."""
    return [i for i in ids if not i.startswith("CAP-")]


def write_csv(rows, ids):
    cols = ["slug", "version", "lane", "installs", "pass", "partial", "fail", "tools"]
    with (HERE / "comparison.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols + judged(ids) + TASKS)
        for r in rows:
            w.writerow([r[c] for c in cols] + [r["checks"].get(i, "") for i in judged(ids)]
                       + [r["tasks"][t] for t in TASKS])


def write_md(rows, ids):
    checks = judged(ids)
    out = [
        "# Comparison",
        "",
        "Generated by `compare.py` from `reviews/`. Do not edit by hand.",
        "",
        "✅ Pass · 🟡 Partial · ❌ Fail · ? Unknown · – N/A. The P / ½ / F columns count the judged checks",
        "with no weighting: read the reviews before drawing conclusions from them.",
        "",
        "## Checks",
        "",
        "| Plugin | Lane | Installs | P | ½ | F | " + " | ".join(checks) + " |",
        "|---|---|--:|--:|--:|--:|" + "|".join([":-:"] * len(checks)) + "|",
    ]
    for r in rows:
        cells = [SHORT.get(r["checks"].get(i, ""), "") for i in checks]
        out.append(f"| {r['slug']} | {r['lane']} | {r['installs']:,} | {r['pass']} | {r['partial']} | {r['fail']} | "
                   + " | ".join(cells) + " |")
    out += [
        "",
        "## Standard tasks",
        "",
        "See `CHECKLIST.md` for what T1–T8 mean. Tools is the tool count with every option on.",
        "",
        "| Plugin | Tools | " + " | ".join(TASKS) + " |",
        "|---|--:|" + "|".join([":-:"] * len(TASKS)) + "|",
    ]
    for r in rows:
        out.append(f"| {r['slug']} | {r['tools']} | " + " | ".join(SHORT.get(r["tasks"][t], "") for t in TASKS) + " |")
    out += ["", "## Totals per check", "", "| Check | Pass | Partial | Fail | Unknown | N/A |", "|---|--:|--:|--:|--:|--:|"]
    for i in checks:
        s = [r["checks"].get(i) for r in rows]
        out.append(f"| {i} | " + " | ".join(str(s.count(x)) for x in ("Pass", "Partial", "Fail", "Unknown", "N/A")) + " |")
    (HERE / "comparison.md").write_text("\n".join(out) + "\n")


def main():
    ids = check_ids()
    rows = load()
    write_csv(rows, ids)
    write_md(rows, ids)
    print(f"{len(rows)} plugins -> comparison.md, comparison.csv")


if __name__ == "__main__":
    main()
