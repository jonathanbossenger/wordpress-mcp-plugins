#!/usr/bin/env python3
"""Combine reviews/*.json into one side-by-side comparison.

Usage:
  python3 compare.py      writes comparison.md, comparison.csv and ranking.md

Each plugin gets one row: its lane and installs from shortlist.csv, a Pass / Partial / Fail
tally over the judged checks, then the status of every check and every standard task.
Rows are sorted by Pass count, then by Fail count (fewer first). The tally is a plain count
with no weighting, so it is a starting point for reading the reviews, not a ranking.

ranking.md is the weighted ranking: see WEIGHTS and GATE below.
"""
import csv
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REVIEWS = HERE / "reviews"
SHORTLIST = HERE / "shortlist.csv"
CHECKLIST = HERE / "CHECKLIST.md"

TASKS = [f"T{n}" for n in range(1, 9)]
SHORT = {"Pass": "✅", "Partial": "🟡", "Fail": "❌", "Unknown": "?", "N/A": "–", "Info": "ℹ️"}

# Ranking: each judged check and each standard task scores Pass 1, Partial ½, Fail 0, times the
# weight of its group. Unknown and N/A are left out. The score is the share of the possible points.
WEIGHTS = {"SEC": 3, "SAFE": 2, "STD": 1.5, "HOST": 1, "SETUP": 1, "DOCS": 1, "T": 1}
POINTS = {"Pass": 1, "Partial": 0.5, "Fail": 0}
# A Fail on any of these puts the plugin below every plugin without one, whatever its score.
GATE = ["SEC-AUTH", "SEC-UNAUTH", "SEC-CAPS", "SEC-SECRETS", "SEC-DEFAULT", "STD-TRANSPORT"]


def check_ids():
    """Check IDs in the order they appear in the checklist tables."""
    return [i for i in re.findall(r"^\| ([A-Z]+(?:-[A-Z]+)?) \|", CHECKLIST.read_text(), re.M) if i != "ID"]


def load():
    shortlist = {r["slug"]: r for r in csv.DictReader(SHORTLIST.open())}
    rows = []
    for path in sorted(REVIEWS.glob("*.json")):
        review = json.loads(path.read_text())
        checks = review["checks"]
        tasks = checks.get("CAP-TASKS", {}).get("value") or {}
        tools = checks.get("CAP-TOOLS", {}).get("value") or {}
        meta = shortlist.get(review["slug"], {})
        statuses = [c["status"] for c in checks.values()]
        rows.append({
            "slug": review["slug"],
            "version": review.get("version", ""),
            "lane": meta.get("lane", ""),
            "installs": int(meta.get("active_installs") or 0),
            "pass": statuses.count("Pass"),
            "partial": statuses.count("Partial"),
            "fail": statuses.count("Fail"),
            "tools": tools.get("count", "") if isinstance(tools, dict) else "",
            "checks": {k: c["status"] for k, c in checks.items()},
            "tasks": {t: (tasks.get(t) or {}).get("status", "") for t in TASKS},
        })
    rows.sort(key=lambda r: (-r["pass"], r["fail"], -r["installs"]))
    return rows


def judged(ids):
    """Checks that carry a judgement (the CAP-* ones are Info)."""
    return [i for i in ids if not i.startswith("CAP-")]


def score(r):
    """Weighted score out of 100 over the judged checks and the standard tasks."""
    statuses = [(i, s) for i, s in r["checks"].items() if not i.startswith("CAP-")] + list(r["tasks"].items())
    got = total = 0
    for i, s in statuses:
        if s in POINTS:
            w = WEIGHTS[i.split("-")[0]] if "-" in i else WEIGHTS["T"]
            got += w * POINTS[s]
            total += w
    return round(100 * got / total, 1) if total else 0.0


def ranked(rows):
    for r in rows:
        r["score"] = score(r)
        r["gated"] = [i for i in GATE if r["checks"].get(i) == "Fail"]
    return sorted(rows, key=lambda r: (bool(r["gated"]), -r["score"], -r["installs"]))


def write_ranking(rows, ids):
    checks = judged(ids)
    label = {"DOCS": "DOCS", "T": "T1–T8"}
    weights = ", ".join(f"{label.get(g, g + '-*')} ×{w:g}" for g, w in WEIGHTS.items())
    out = [
        "# Ranking",
        "",
        "Generated by `compare.py` from `reviews/`. Do not edit by hand.",
        "",
        "How the score works:",
        "",
        f"- Each judged check and each standard task (T1–T8) scores Pass 1, Partial ½, Fail 0, weighted by group: {weights}.",
        "  Unknown and N/A are left out. The score is the share of the possible points, out of 100.",
        f"- A Fail on any of {', '.join(GATE)} ranks the plugin below every plugin without one, whatever its score.",
        "- Ties are broken by active installs.",
        "- Everything is judged from the code. Nothing has been tested on a real site yet, so treat positions that",
        "  are a point or two apart as level.",
        "",
        "| # | Plugin | Lane | Installs | Score | P | ½ | F | Tasks ✅ | Excluded by | Fails |",
        "|--:|---|---|--:|--:|--:|--:|--:|--:|---|---|",
    ]
    for n, r in enumerate(rows, 1):
        fails = [i for i in checks if r["checks"].get(i) == "Fail"] + [t for t in TASKS if r["tasks"][t] == "Fail"]
        tasks_passed = sum(r["tasks"][t] == "Pass" for t in TASKS)
        out.append(f"| {n} | {r['slug']} | {r['lane']} | {r['installs']:,} | {r['score']:.1f} | {r['pass']} | {r['partial']} "
                   f"| {r['fail']} | {tasks_passed}/8 | {', '.join(r['gated'])} | {', '.join(fails)} |")
    out += ["", "P / ½ / F count the judged checks only, as in `comparison.md`. Fails lists failed checks and tasks."]
    (HERE / "ranking.md").write_text("\n".join(out) + "\n")


def write_csv(rows, ids):
    cols = ["slug", "version", "lane", "installs", "pass", "partial", "fail", "tools"]
    with (HERE / "comparison.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols + judged(ids) + TASKS)
        for r in rows:
            w.writerow([r[c] for c in cols] + [r["checks"].get(i, "") for i in judged(ids)]
                       + [r["tasks"][t] for t in TASKS])


def write_md(rows, ids):
    checks = judged(ids)
    out = [
        "# Comparison",
        "",
        "Generated by `compare.py` from `reviews/`. Do not edit by hand.",
        "",
        "✅ Pass · 🟡 Partial · ❌ Fail · ? Unknown · – N/A. The P / ½ / F columns count the judged checks",
        "with no weighting: read the reviews before drawing conclusions from them.",
        "",
        "## Checks",
        "",
        "| Plugin | Lane | Installs | P | ½ | F | " + " | ".join(checks) + " |",
        "|---|---|--:|--:|--:|--:|" + "|".join([":-:"] * len(checks)) + "|",
    ]
    for r in rows:
        cells = [SHORT.get(r["checks"].get(i, ""), "") for i in checks]
        out.append(f"| {r['slug']} | {r['lane']} | {r['installs']:,} | {r['pass']} | {r['partial']} | {r['fail']} | "
                   + " | ".join(cells) + " |")
    out += [
        "",
        "## Standard tasks",
        "",
        "See `CHECKLIST.md` for what T1–T8 mean. Tools is the tool count with every option on.",
        "",
        "| Plugin | Tools | " + " | ".join(TASKS) + " |",
        "|---|--:|" + "|".join([":-:"] * len(TASKS)) + "|",
    ]
    for r in rows:
        out.append(f"| {r['slug']} | {r['tools']} | " + " | ".join(SHORT.get(r["tasks"][t], "") for t in TASKS) + " |")
    out += ["", "## Totals per check", "", "| Check | Pass | Partial | Fail | Unknown | N/A |", "|---|--:|--:|--:|--:|--:|"]
    for i in checks:
        s = [r["checks"].get(i) for r in rows]
        out.append(f"| {i} | " + " | ".join(str(s.count(x)) for x in ("Pass", "Partial", "Fail", "Unknown", "N/A")) + " |")
    (HERE / "comparison.md").write_text("\n".join(out) + "\n")


def main():
    ids = check_ids()
    rows = load()
    write_csv(rows, ids)
    write_md(rows, ids)
    write_ranking(ranked(rows), ids)
    print(f"{len(rows)} plugins -> comparison.md, comparison.csv, ranking.md")


if __name__ == "__main__":
    main()
